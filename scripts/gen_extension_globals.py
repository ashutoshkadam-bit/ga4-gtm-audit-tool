"""Regenerates extension/globals.js from gga/techdb.py so the extension probes the same JavaScript globals as the tool.
Run after editing the signature list:  python scripts/gen_extension_globals.py
"""
import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root))
from gga import pagecapture  # noqa: E402

names = pagecapture._globals_to_probe()  # noqa: SLF001
out = root / "extension" / "globals.js"
out.write_text("// Generated by scripts/gen_extension_globals.py from gga/techdb.py. Do not edit by hand.\n"
               "window.__GGA_GLOBALS = " + json.dumps(names) + ";\n", encoding="utf-8")
print(f"wrote {out} with {len(names)} names")
